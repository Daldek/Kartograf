"""Public API typing contract (PEP 561, ``py.typed``).

A consumer type-checking its adapter with ``mypy --strict`` must see complete,
precise annotations on everything in ``kartograf.__all__``: no unannotated
parameter or return and no bare generic (``tuple``, ``dict``, ``list``, ...).
Two checks guard that: an ``inspect`` walk over the public callables and
dataclass fields, and a real mypy run over a small consumer module that uses
the API the way the Archiwista adapter does (explicitly typed variables, so a
wrong return type fails the run).
"""

import inspect
import re
import sys
import textwrap
import typing
from pathlib import Path

import pytest
from mypy import api as mypy_api

import kartograf

ROOT = Path(__file__).resolve().parents[1]

# Generated by ``typing.NamedTuple`` / ``dataclass``; not part of the contract.
_GENERATED = {"_make", "__new__"}

# Builtin containers that must always be parameterised in an annotation.
_BARE_CONTAINERS = {tuple, dict, list, set, frozenset}


def _public_callables() -> list[tuple[str, typing.Callable[..., object]]]:
    """Functions and public methods of ``kartograf.__all__``: ``(label, function)``."""
    found: list[tuple[str, typing.Callable[..., object]]] = []
    for name in kartograf.__all__:
        obj = getattr(kartograf, name)
        if inspect.isclass(obj):
            for member_name, member in vars(obj).items():
                if member_name in _GENERATED:
                    continue
                if member_name.startswith("_") and member_name != "__init__":
                    continue
                if isinstance(member, (staticmethod, classmethod)):
                    member = member.__func__
                elif isinstance(member, property):
                    member = member.fget
                if inspect.isfunction(member):
                    found.append((f"{name}.{member_name}", member))
        elif inspect.isfunction(inspect.unwrap(obj)):
            found.append((name, obj))  # includes functools.lru_cache wrappers
    return found


def _is_generic_class(tp: object) -> typing.TypeGuard[type]:
    """Whether ``tp`` is a class that takes type arguments.

    ``Generic`` subclasses carry ``__parameters__`` (empty when fully applied, so
    NamedTuples, Protocols and ``BinaryIO`` are not generic); builtin generics
    (``dict``, ``ndarray``, ``collections.abc`` ABCs) have none and are
    recognised by ``__class_getitem__``.
    """
    if not isinstance(tp, type) or tp is type:
        return False
    if hasattr(tp, "__parameters__"):
        return bool(tp.__parameters__)
    return tp in _BARE_CONTAINERS or (
        hasattr(tp, "__class_getitem__") and not issubclass(tp, tuple)
    )


def _bare_generics(tp: object) -> list[str]:
    """Names of generic types used without type arguments inside ``tp``."""
    origin = typing.get_origin(tp)
    args = typing.get_args(tp)
    if origin is None:
        if _is_generic_class(tp):
            return [f"{tp.__module__}.{tp.__qualname__}"]
        return []
    if origin is typing.Literal:
        return []
    if not args and _is_generic_class(origin):
        return [f"{origin.__module__}.{origin.__qualname__}"]
    out: list[str] = []
    for arg in args:
        # ``Callable[[int], str]`` keeps its parameter list as a list.
        items = arg if isinstance(arg, list) else [arg]
        for item in items:
            out.extend(_bare_generics(item))
    return out


def _hints(obj: object) -> dict[str, object]:
    try:
        return typing.get_type_hints(obj, include_extras=True)
    except NameError:
        # An annotation naming a TYPE_CHECKING-only import; mypy still sees it.
        return {}


def test_public_callables_fully_annotated() -> None:
    missing: list[str] = []
    for label, fn in _public_callables():
        signature = inspect.signature(fn)
        for parameter in signature.parameters.values():
            if parameter.name in ("self", "cls"):
                continue
            if parameter.annotation is inspect.Parameter.empty:
                missing.append(f"{label}: parameter '{parameter.name}'")
        if label.endswith(".__init__"):
            continue  # __init__ -> None is implied by mypy when a parameter is typed
        if signature.return_annotation is inspect.Signature.empty:
            missing.append(f"{label}: return")
    assert not missing, "unannotated public API:\n" + "\n".join(sorted(missing))


def test_public_api_has_no_bare_generics() -> None:
    bare: list[str] = []
    for label, fn in _public_callables():
        for annotated, tp in _hints(fn).items():
            bare.extend(f"{label}: {annotated} -> bare {b}" for b in _bare_generics(tp))
    for name in kartograf.__all__:
        obj = getattr(kartograf, name)
        if not inspect.isclass(obj):
            continue
        for field_name, tp in _hints(obj).items():
            if field_name.startswith("_"):
                continue
            bare.extend(f"{name}.{field_name}: bare {b}" for b in _bare_generics(tp))
    assert not bare, "bare generics in the public API:\n" + "\n".join(sorted(bare))


_CLEAN_CONSUMER = textwrap.dedent(
    '''
    """Archiwista-style consumer: every variable is annotated on purpose."""

    from collections.abc import Iterator
    from concurrent.futures import ThreadPoolExecutor
    from pathlib import Path

    import numpy as np
    import numpy.typing as npt

    import kartograf
    from kartograf import (
        AvailabilityReport,
        BBox,
        DataReport,
        MetadataCache,
        Notice,
        PinnedTransform,
        SegmentInfo,
        Sidecar,
        StoreEntry,
    )
    from kartograf.catalog.model import Catalog
    from kartograf.commands import CommandCall
    from kartograf.providers.pl import GugikProvider, create_nmt_provider
    from kartograf.store_geometry import Footprint


    def store(root: Path, cache: dict[tuple[str, str], BBox]) -> None:
        segments: list[str] = kartograf.list_segments(root)
        info: SegmentInfo = kartograf.describe_segment(segments[0])
        name: str = info.name
        partitions: list[str] = kartograf.list_partitions(root, segments[0], target=8)
        entries: Iterator[StoreEntry] = kartograf.iter_store(
            root,
            segment=segments[0],
            partition=partitions[0],
            skip_versions={"a": ["b"]},
        )
        for entry in entries:
            path: Path = entry.path
            embedded: Sidecar | None = entry.sidecar
            sidecar: Sidecar = kartograf.read_sidecar(path)
            product: str | None = sidecar.product
            footprint: Footprint | None = kartograf.file_footprint(
                entry, network=False, cache=cache
            )
            if footprint is not None:
                native: BBox = footprint.native
                source: str = footprint.source
            target: Path | None = kartograf.link_target(path)
            print(name, embedded, product, native, source, target)


    def transforms(xs: npt.NDArray[np.float64]) -> None:
        pinned: PinnedTransform = kartograf.pinned_transform("EPSG:2180", "EPSG:4326")
        point: tuple[float, float] = pinned.transform(500000.0, 300000.0)
        point3: tuple[float, float, float] = pinned.transform(1.0, 2.0, 3.0)
        arrays: tuple[npt.NDArray[np.float64], npt.NDArray[np.float64]] = (
            pinned.transform(xs, xs)
        )
        arrays3: tuple[
            npt.NDArray[np.float64], npt.NDArray[np.float64], npt.NDArray[np.float64]
        ] = pinned.transform(xs, xs, xs)
        with ThreadPoolExecutor() as pool:
            future = pool.submit(pinned.transform, 1.0, 2.0)
            from_pool: tuple[float, float] = future.result()
        pipeline: str = pinned.gdal_operation()
        print(point, point3, arrays, arrays3, from_pool, pipeline)


    def services(root: Path, cache: MetadataCache | None) -> None:
        provider: GugikProvider = create_nmt_provider("EVRF2007", "1m", cache=cache)
        print(provider.name)
        report: AvailabilityReport = kartograf.check_availability(
            product="nmt", sheet="N-34-130-D-d-2-4", cache=False
        )
        ok: bool = report.ok
        notices: tuple[Notice, ...] = report.notices
        catalog: Catalog = kartograf.get_catalog(group=None, params=True)
        call: CommandCall = kartograf.parse_command("nmt --sheet N-34-130-D-d-2-4")
        line: str = kartograf.format_command(call.command, call.options, run=call.run)
        result: DataReport = kartograf.download_data(
            product="nmt", output_dir=root, sheet="N-34-130-D-d-2-4"
        )
        print(ok, notices, catalog, line, result)
    '''
)

# Every statement below must be rejected: the annotations are precise enough
# that a wrong consumer expectation is a type error, not an implicit Any.
_BAD_CONSUMER = textwrap.dedent(
    """
    from pathlib import Path

    import kartograf

    segments: list[int] = kartograf.list_segments(Path("."))  # BAD list_segments
    pinned = kartograf.pinned_transform("EPSG:2180", "EPSG:4326")
    triple: tuple[float, float, float] = pinned.transform(1.0, 2.0)  # BAD transform
    pinned.transform("x", "y")  # BAD argument type
    kartograf.link_target(Path(".")).exists()  # BAD optional
    """
)


def _error_file(line: str) -> str:
    return Path(line.split(":", 1)[0]).name


def test_consumer_strict_mypy(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    # This checkout wins over any editable install of another checkout.
    monkeypatch.setenv("MYPYPATH", str(ROOT))
    clean = tmp_path / "consumer_clean.py"
    bad = tmp_path / "consumer_bad.py"
    clean.write_text(_CLEAN_CONSUMER, encoding="utf-8")
    bad.write_text(_BAD_CONSUMER, encoding="utf-8")
    stdout, stderr, status = mypy_api.run(
        [
            "--strict",
            "--follow-imports=silent",
            "--config-file=",
            "--python-executable",
            sys.executable,
            "--cache-dir",
            str(ROOT / ".mypy_cache" / "consumer"),
            str(clean),
            str(bad),
        ]
    )
    assert stderr == ""
    errors = [line for line in stdout.splitlines() if ": error:" in line]
    # mypy prints paths relative to the cwd when it can; match on the file name.
    clean_errors = [line for line in errors if _error_file(line) == clean.name]
    assert not clean_errors, "consumer module is not strict-clean:\n" + "\n".join(
        clean_errors
    )
    bad_lines = {
        int(m.group(1))
        for line in errors
        if _error_file(line) == bad.name
        and (m := re.match(r"[^:]*:(\d+): error", line))
    }
    expected = {
        number
        for number, line in enumerate(_BAD_CONSUMER.splitlines(), 1)
        if "# BAD" in line
    }
    assert status == 1
    assert bad_lines == expected
