"""``kartograf script``: the scripts of a request for the user's own machine (ADR-063).

``script generate`` writes a bash or PowerShell script of the line of a data command:
the Kartograf script that runs it, or with ``direct`` the script of the URLs of its
plan (or of a saved plan). Nothing is resolved or written; the network only plans a
direct script of a line.
"""

from kartograf.catalog import shared
from kartograf.catalog.spec import Command, Constraint, Example, Group, Param
from kartograf.messages import message


def _shells() -> tuple[str, ...]:
    from kartograf.script import SHELLS  # it imports the catalog

    return SHELLS


_LINE = (
    "elevation download --product nmt --sheet N-34-130-D-d-2-4 --resolution 1m "
    "--vertical-crs EVRF2007 -o ./dem"
)

COMMANDS = (
    Command(
        "script generate",
        message("catalog_script.generate_summary"),
        "query",
        "generate_script",
        "kartograf-script/1",
        (
            Param(
                "shell",
                "str",
                message("catalog_script.shell_description"),
                required=True,
                allowed=_shells,
                choices=True,
                normalize="lower",
                metavar=message("catalog_script.metavar_shell"),
            ),
            Param(
                "command",
                "str",
                message("catalog_script.command_description"),
                # not the group of the line (``command`` of the namespace)
                dest="command_line",
                metavar=message("catalog_script.metavar_line"),
                examples=(_LINE,),
            ),
            Param(
                "plan",
                "plan",
                message("catalog_script.plan_description"),
                metavar=message("catalog.metavar_file"),
            ),
            Param(
                "direct",
                "flag",
                message("catalog_script.direct_description"),
                default=False,
            ),
            Param(
                "target",
                "str",
                message("catalog_script.target_description"),
                metavar=message("catalog.metavar_directory"),
            ),
            shared.JSON,
        ),
        description=message("catalog_script.generate_description"),
        effects=("network",),
        constraints=(
            Constraint(
                "one_of",
                ("command", "plan"),
                message("catalog_script.rule_command_or_plan"),
                group="request",
            ),
            Constraint(
                "requires",
                ("direct",),
                message("script.plan_needs_direct"),
                "plan",
            ),
            Constraint(
                "requires",
                ("direct",),
                message("script.target_needs_direct"),
                "target",
            ),
        ),
        examples=(
            Example(
                {"shell": "bash", "command": _LINE},
                title=message("catalog_script.example_kartograf_bash"),
                result={
                    "schema": "kartograf-script/1",
                    "shell": "bash",
                    "kind": "kartograf",
                    "text": "#!/usr/bin/env bash\n# Generated by kartograf script "
                    "generate (Kartograf 0.9.0).\n...",
                    "files": [],
                    "left_out": [],
                },
            ),
            Example(
                {
                    "shell": "powershell",
                    "command": _LINE,
                    "direct": True,
                    "target": "C:/data/nmt",
                },
                title=message("catalog_script.example_direct_powershell"),
            ),
        ),
        rules=(message("catalog_script.generate_rule"),),
        errors=(
            "validation_error",
            "unsupported",
            "source_unavailable",
            "no_data",
            "calculation_error",
            "store_unavailable",
            "io_error",
        ),
        family="data",
    ),
)

GROUPS = (
    Group(
        "script",
        message("catalog_script.group_summary"),
        message("catalog_script.group_description"),
        position=2,
    ),
)
